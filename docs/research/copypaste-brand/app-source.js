function getCanonicalPagePath(pathname) {
  if (
    pathname === "/" ||
    pathname === "/index.html" ||
    pathname === "/zh-hans" ||
    pathname === "/zh-hans/" ||
    pathname === "/zh-hant" ||
    pathname === "/zh-hant/"
  ) {
    return "/";
  }

  if (pathname.startsWith("/zh-hans/")) {
    return pathname.replace("/zh-hans", "");
  }

  if (pathname.startsWith("/zh-hant/")) {
    return pathname.replace("/zh-hant", "");
  }

  return pathname;
}

function getLocalizedPath(path, lang) {
  const hashIndex = path.indexOf("#");
  const pathname = hashIndex >= 0 ? path.slice(0, hashIndex) : path;
  const hash = hashIndex >= 0 ? path.slice(hashIndex) : "";
  const canonical = getCanonicalPagePath(stripBasePath(pathname));

  if (!localizablePaths.has(canonical)) {
    return prefixPath(path);
  }

  let localized = canonical;
  if (lang === "en") {
    localized = canonical === "/" ? "/" : canonical;
  } else if (canonical === "/") {
    localized = `/${lang}/`;
  } else {
    localized = `/${lang}${canonical}`;
  }

  return prefixPath(localized) + hash;
}

function localizeInternalLinks() {
  const links = document.querySelectorAll("main a[href]");
  links.forEach((link) => {
    const href = link.getAttribute("href");
    if (!href || href.startsWith("#") || href.startsWith("http") || href.startsWith("mailto:") || href.startsWith("tel:")) {
      return;
    }

    if (href.startsWith("/")) {
      link.setAttribute("href", getLocalizedPath(href, currentLang));
    }
  });
}

function initLanguageSwitcher() {
  const dropdowns = document.querySelectorAll("[data-lang-dropdown]");
  const triggers = document.querySelectorAll("[data-lang-trigger]");
  const links = document.querySelectorAll("[data-lang-option]");

  const closeDropdowns = () => {
    dropdowns.forEach((dropdown) => {
      dropdown.classList.remove("is-open");
    });
    triggers.forEach((trigger) => {
      trigger.setAttribute("aria-expanded", "false");
    });
  };

  triggers.forEach((trigger) => {
    trigger.addEventListener("click", (event) => {
      event.stopPropagation();
      const dropdown = trigger.closest("[data-lang-dropdown]");
      const isOpen = dropdown?.classList.toggle("is-open");
      triggers.forEach((item) => {
        item.setAttribute("aria-expanded", item === trigger && isOpen ? "true" : "false");
      });
    });
  });

  document.addEventListener("click", closeDropdowns);
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeDropdowns();
    }
  });

  links.forEach((link) => {
    link.addEventListener("click", () => {
      window.localStorage.setItem(langKey, link.dataset.langOption);
      closeDropdowns();
    });
  });
}

function initTheme() {
  const storedTheme = window.localStorage.getItem(themeKey);
  if (storedTheme === "light" || storedTheme === "dark") {
    applyTheme(storedTheme);
    return;
  }

  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  applyTheme(prefersDark ? "dark" : "light");
}

function initThemeToggle() {
  const toggles = document.querySelectorAll("[data-theme-toggle]");
  const media = window.matchMedia("(prefers-color-scheme: dark)");

  toggles.forEach((toggle) => {
    toggle.addEventListener("click", () => {
      const nextTheme = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
      window.localStorage.setItem(themeKey, nextTheme);
      applyTheme(nextTheme);
      syncThemeToggleText();
    });
  });

  const handleSchemeChange = (event) => {
    const savedTheme = window.localStorage.getItem(themeKey);
    if (!savedTheme) {
      applyTheme(event.matches ? "dark" : "light");
      syncThemeToggleText();
    }
  };

  if (typeof media.addEventListener === "function") {
    media.addEventListener("change", handleSchemeChange);
  } else if (typeof media.addListener === "function") {
    media.addListener(handleSchemeChange);
  }

  syncThemeToggleText();
}

function applyTheme(theme) {
  document.documentElement.dataset.theme = theme;
  syncBrandLogo(theme);
}

function syncThemeToggleText() {
  const toggles = document.querySelectorAll("[data-theme-toggle]");
  const isDark = document.documentElement.dataset.theme === "dark";
  const toggleLabel = isDark ? siteConfig.themeToLight : siteConfig.themeToDark;

  toggles.forEach((toggle) => {
    const text = toggle.querySelector(".theme-label");
    if (text) {
      text.textContent = isDark ? siteConfig.themeTextDark : siteConfig.themeTextLight;
    }
    toggle.setAttribute("aria-label", toggleLabel);
    toggle.setAttribute("title", toggleLabel);
  });
}

function syncBrandLogo(theme) {
  const logos = document.querySelectorAll("[data-brand-logo]");
  const mode = theme === "dark" ? "dark" : "light";
  const target = logoAssets[mode];

  logos.forEach((logo) => {
    logo.onerror = null;
    logo.src = target.png;
    logo.onerror = () => {
      logo.onerror = null;
      logo.src = target.png;
    };
  });
}

