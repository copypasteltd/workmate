function hideConsultationButtons() {
  const labels = new Set(["Book a Consultation", "预约咨询", "預約諮詢"]);
  const nodes = document.querySelectorAll("a, button");

  nodes.forEach((node) => {
    const text = node.textContent?.trim();
    if (!text || !labels.has(text)) {
      return;
    }

    node.style.display = "none";
    node.setAttribute("aria-hidden", "true");
  });
}

function detectCurrentLang() {
  const path = stripBasePath(window.location.pathname);
  if (path === "/zh-hans" || path.startsWith("/zh-hans/")) {
    return "zh-hans";
  }
  if (path === "/zh-hant" || path.startsWith("/zh-hant/")) {
    return "zh-hant";
  }
  return "en";
}

function initAutoLanguageRedirect() {
  const path = stripBasePath(window.location.pathname);
  const canonicalPath = getCanonicalPagePath(path);

  if (currentLang !== "en" || !localizablePaths.has(canonicalPath)) {
    return;
  }

  const storedLang = window.localStorage.getItem(langKey);
  const targetLang = storedLang || detectBrowserLang();

  if (targetLang !== "en") {
    window.location.replace(getLocalizedPath(canonicalPath + window.location.hash, targetLang));
  }
}

function detectBrowserLang() {
  const language = (navigator.language || "").toLowerCase();
  if (language.includes("zh")) {
    if (language.includes("hant") || language.includes("hk") || language.includes("mo") || language.includes("tw")) {
      return "zh-hant";
    }
    return "zh-hans";
  }
  return "en";
}

