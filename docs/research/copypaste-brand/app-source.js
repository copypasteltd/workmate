function stripBasePath(pathname) {
  if (pathname === BASE_PATH || pathname === `${BASE_PATH}/`) {
    return "/";
  }
  if (pathname.startsWith(`${BASE_PATH}/`)) {
    return pathname.slice(BASE_PATH.length);
  }
  return pathname;
}

function prefixPath(path) {
  if (!path || !path.startsWith("/") || path.startsWith(`${BASE_PATH}/`) || path.startsWith("/assets/")) {
    return path;
  }
  return `${BASE_PATH}${path}`;
}

function normalizeConfigPaths() {
  Object.values(localizedConfig).forEach((config) => {
    config.nav = config.nav.map((item) => ({
      ...item,
      href: prefixPath(item.href)
    }));
    config.ctas = config.ctas.map((item) => ({
      ...item,
      href: prefixPath(item.href)
    }));
    config.footer.serviceLinks = config.footer.serviceLinks.map((item) => ({
      ...item,
      href: prefixPath(item.href)
    }));
  });
}
