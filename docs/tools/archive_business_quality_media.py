"""Relocate only this increment's unselected, untracked captures without deleting bytes."""
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
DEV = ROOT / 'dev'
ARCHIVE = DEV / 'copypaste-delivery/.data/unselected-business-quality-media'
OUTPUT = ROOT / 'docs/quality/business-quality-unselected-media.json'
PREFIXES = {
    'desktop': ('workmate-local-29-', 'workmate-local-30-'),
    'web': ('workmate-quality-03-', 'workmate-quality-05-', 'workmate-quality-06-'),
    'admin': ('workmate-quality-03-', 'workmate-quality-05-', 'workmate-quality-06-'),
    'extension': ('workmate-chat-06-',),
}


def main():
    assert not OUTPUT.exists() and ARCHIVE.resolve().is_relative_to(DEV.resolve())
    planned = []
    for component, prefixes in PREFIXES.items():
        repo = DEV / ('copypaste-' + component)
        folder = repo / 'assets/screenshots'
        tracked = subprocess.run(['git', '-c', 'core.fsmonitor=false', '-c', 'core.untrackedCache=false', 'ls-files', '-z', '--', 'assets/screenshots'], cwd=repo, check=True, capture_output=True).stdout
        tracked = {p.decode('utf-8') for p in tracked.split(b'\0') if p}
        for source in sorted(folder.iterdir()):
            if not source.name.startswith(prefixes):
                continue
            assert source.is_file() and not source.is_symlink() and source.resolve().is_relative_to(folder.resolve())
            assert source.relative_to(repo).as_posix() not in tracked, 'Never move published or pre-existing tracked captures'
            target = ARCHIVE / component / source.name
            assert target.resolve().is_relative_to(ARCHIVE.resolve()) and not target.exists()
            planned.append((source, target, sha256(source.read_bytes()).hexdigest()))
    assert planned
    records = []
    for source, target, expected in planned:
        target.parent.mkdir(parents=True, exist_ok=True)
        source.rename(target)
        assert sha256(target.read_bytes()).hexdigest() == expected and not source.exists()
        records.append({'original_path': source.relative_to(ROOT).as_posix(), 'local_archive_path': target.relative_to(ROOT).as_posix(), 'sha256': expected, 'bytes': target.stat().st_size})
    result = {'at': datetime.now(timezone.utc).isoformat(), 'status': 'relocated_without_byte_changes',
              'scope': 'Only untracked media generated by unselected stage78 attempts. Raw immutable receipts remain; their old media paths resolve through this ledger. Binary archives are local ignored artifacts, not selected README evidence.',
              'selected_attempts': {'desktop': '31', 'web_admin': '07', 'extension': '07'}, 'files': records,
              'recursive_deletion': False, 'verifier_sha256': sha256(Path(__file__).read_bytes()).hexdigest()}
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'status': result['status'], 'files': len(records)}))


if __name__ == '__main__':
    main()
